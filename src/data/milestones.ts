export interface MilestoneEffect {
  /** Порог, на котором открывается бонус. */
  threshold: 50 | 100;
  title: string;
  kind: 'Актив' | 'Пассив';
  /** Условия активации (для активов): «часть атаки, 1 Выносливости». */
  activation?: string;
  /** Сколько Выносливости тратит актив (для кнопки «Применить»). */
  stamina?: number;
  /** Можно применить один раз в день — до «Нового дня». */
  daily?: boolean;
  /** Что восстанавливает при применении (считается автоматически, см. applyMilestoneRestore). */
  restore?: MilestoneRestore;
  text: string;
}

type MilestoneDef = Omit<MilestoneEffect, 'threshold'>;

